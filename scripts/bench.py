"""Measure what the demo claims: per-stage latency, warm and cold.

Writes docs/LATENCY.md. Two numbers are reported separately on purpose --
the first call pays for loading models and the rest do not, and averaging the
two together would produce a figure that describes neither.

    python scripts/bench.py                 # all fixtures, whisper small
    python scripts/bench.py --sizes small,medium
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import ssl
import sys
import time
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
# The demo may be served over HTTPS with a self-signed certificate (see
# scripts/serve.py). Point at it with DISPATCHIQ_API, and do not verify the
# chain: it is signed by nobody on purpose, and this only ever talks to a
# server on this machine.
BASE = os.environ.get("DISPATCHIQ_API", "http://127.0.0.1:8000").rstrip("/")
SSL_CONTEXT = ssl._create_unverified_context() if BASE.startswith("https") else None


def _open(request, timeout):
    return urllib.request.urlopen(request, timeout=timeout, context=SSL_CONTEXT)


def post_audio(session_id: str, wav: Path, size: str) -> tuple[dict, float]:
    boundary = "----dispatchiqbench"
    payload = json.dumps({"session_id": session_id, "whisper_size": size})
    body = b"".join([
        f"--{boundary}\r\n".encode(),
        b'Content-Disposition: form-data; name="payload"\r\n\r\n',
        payload.encode() + b"\r\n",
        f"--{boundary}\r\n".encode(),
        f'Content-Disposition: form-data; name="audio"; filename="{wav.name}"\r\n'.encode(),
        b"Content-Type: audio/wav\r\n\r\n",
        wav.read_bytes() + b"\r\n",
        f"--{boundary}--\r\n".encode(),
    ])
    request = urllib.request.Request(
        BASE + "/api/process",
        data=body,
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"},
    )
    started = time.perf_counter()
    with _open(request, 900) as response:
        data = json.loads(response.read())
    return data, (time.perf_counter() - started) * 1000


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", default="small")
    parser.add_argument("--repeats", type=int, default=2, help="warm runs per fixture")
    args = parser.parse_args()

    with _open(urllib.request.Request(BASE + "/api/health"), 60) as response:
        health = json.loads(response.read())

    index = json.loads((REPO / "fixtures" / "index.json").read_text(encoding="utf-8"))
    rows: list[dict] = []

    for size in [s.strip() for s in args.sizes.split(",") if s.strip()]:
        for scenario in index:
            sid = scenario["id"]
            wav = REPO / "fixtures" / "audio" / f"{sid}.wav"
            if not wav.exists():
                continue

            cold, cold_wall = post_audio(f"bench-cold-{size}-{sid}", wav, size)
            warm_runs = [
                post_audio(f"bench-warm-{size}-{sid}-{i}", wav, size)
                for i in range(args.repeats)
            ]

            def median(key: str) -> float:
                return statistics.median(d["latency_ms"][key] for d, _ in warm_runs)

            rows.append({
                "fixture": sid,
                "language": scenario["language"],
                "whisper": size,
                "cold_total": round(cold["latency_ms"]["server_total"]),
                "asr": round(median("asr")),
                "decision": round(median("decision")),
                "server_total": round(median("server_total")),
                "wall": round(statistics.median(w for _, w in warm_runs)),
                "action": cold["suggested_action"],
            })
            print(f"- {sid:26} {size:7} cold {rows[-1]['cold_total']:>6}ms  "
                  f"warm {rows[-1]['server_total']:>6}ms  "
                  f"(asr {rows[-1]['asr']}, decision {rows[-1]['decision']})")

    lines = [
        "# Measured latency",
        "",
        "Generated by `python scripts/bench.py`. Numbers are from this machine;",
        "re-run on yours before quoting them.",
        "",
        f"- Whisper: `{health['whisper']['device']}` / `{health['whisper']['compute_type']}`",
        f"- Laya checkpoint: `{health['laya']['checkpoint']}`",
        "",
        "Cold and warm are reported separately. The first call to a model pays for",
        "loading it; every later call does not. A single averaged figure would",
        "describe neither case.",
        "",
        "| fixture | lang | whisper | cold total | warm ASR | warm decision | warm total |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['fixture']} | {row['language']} | {row['whisper']} | "
            f"{row['cold_total']} ms | {row['asr']} ms | {row['decision']} ms | "
            f"{row['server_total']} ms |"
        )

    if rows:
        lines += [
            "",
            f"Median warm end-to-end across fixtures: "
            f"**{round(statistics.median(r['server_total'] for r in rows))} ms**, of which "
            f"**{round(statistics.median(r['decision'] for r in rows))} ms** is the decision engine.",
            "",
            "The decision figure is the part that matters for the claim that typed",
            "decisions are cheap: it covers Laya answering twelve questions in both",
            "languages plus the deterministic extractor. Speech recognition dominates",
            "the total, and it scales with clip length rather than with question count.",
        ]

    out = REPO / "docs" / "LATENCY.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
